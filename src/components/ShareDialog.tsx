"use client";

import { useEffect, useRef, useState } from "react";
import QRCode from "qrcode";
import { CheckIcon, CopyIcon } from "./icons";

type Props = {
  /** Full address of this room. */
  url: string;
  status: "connecting" | "live" | "offline";
  onClose: () => void;
};

const STATUS_TEXT = {
  live: "Synced",
  connecting: "Connecting…",
  offline: "Offline. Changes will sync when you are back online.",
};

/** Shows the room link with a copy button and a QR code of the same address. */
export default function ShareDialog({ url, status, onClose }: Props) {
  const [copied, setCopied] = useState(false);
  const [qr, setQr] = useState("");
  const input = useRef<HTMLInputElement>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  useEffect(() => {
    let live = true;
    QRCode.toString(url, { type: "svg", margin: 0, errorCorrectionLevel: "M", color: { dark: "#000000", light: "#ffffff" } })
      .then((svg) => live && setQr(svg))
      .catch(() => {});
    return () => {
      live = false;
    };
  }, [url]);

  useEffect(
    () => () => {
      if (timer.current) clearTimeout(timer.current);
    },
    [],
  );

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(url);
    } catch {
      // Older browsers and plain-http pages: select the text and use the legacy command.
      input.current?.select();
      try {
        document.execCommand("copy");
      } catch {
        return;
      }
    }
    setCopied(true);
    if (timer.current) clearTimeout(timer.current);
    timer.current = setTimeout(() => setCopied(false), 1800);
  };

  return (
    <div className="overlay" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className="dialog share" role="dialog" aria-modal aria-label="Share this room">
        <h2>Share this room</h2>

        <p className="share-note">
          Anyone with this link sees the same topics and timers, live. Send it to your other devices or to people you
          share your time with.
        </p>

        <div className="share-url">
          <input ref={input} readOnly value={url} aria-label="Room link" onFocus={(e) => e.currentTarget.select()} />
          <button
            className={`share-copy${copied ? " done" : ""}`}
            onClick={copy}
            aria-label={copied ? "Link copied" : "Copy link"}
            title={copied ? "Copied" : "Copy link"}
          >
            {copied ? <CheckIcon size={16} /> : <CopyIcon />}
          </button>
        </div>

        <div className="share-qr">
          <div
            className="qr"
            role="img"
            aria-label="QR code for the room link"
            dangerouslySetInnerHTML={{ __html: qr }} // SVG generated by the qrcode library from the address above
          />
          <p>Scan with your phone camera to open this room.</p>
        </div>

        <p className="share-warn">Anyone who has the link can change this room, so share it only with people you trust.</p>

        <div className="share-status">
          <span className={`sync-dot sync-${status}`} aria-hidden /> {STATUS_TEXT[status]}
        </div>

        <div className="actions">
          <span className="spacer" />
          <button type="button" className="btn-text cancel-btn" onClick={onClose}>
            Cancel
          </button>
        </div>
      </div>
    </div>
  );
}
